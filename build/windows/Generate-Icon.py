#!/usr/bin/env python3
"""Generate or validate Vkit's Windows icon from design/logo.png.

The PNG is the only editable source.  Each ICO frame is an explicit RGBA
Lanczos resize, stored as PNG inside the ICO container.  ``--check`` performs
a pixel-for-pixel validation; ``--write`` updates both the ICO and the small
hash manifest consumed by ``vkit_app/build.rs``.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import struct
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError as exc:  # pragma: no cover - environment-specific failure
    raise SystemExit(
        "Pillow is required to generate Vkit's icon: python -m pip install Pillow"
    ) from exc

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "design" / "logo.png"
ICO = ROOT / "native" / "vkit_app" / "resources" / "vkit.ico"
MANIFEST = ICO.with_name("vkit-icon.sha256")
SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)
SCHEMA = "vkit-icon-v1"
RESAMPLE = "rgba-lanczos"

def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def expected_frames(source: Image.Image) -> list[tuple[int, bytes, bytes]]:
    rgba = source.convert("RGBA")
    frames: list[tuple[int, bytes, bytes]] = []
    for size in SIZES:
        frame = rgba.resize((size, size), Image.Resampling.LANCZOS)
        encoded = io.BytesIO()
        frame.save(encoded, format="PNG")
        frames.append((size, frame.tobytes(), encoded.getvalue()))
    return frames

def encode_ico(frames: list[tuple[int, bytes, bytes]]) -> bytes:
    directory_size = 6 + 16 * len(frames)
    offset = directory_size
    entries: list[bytes] = []
    payloads: list[bytes] = []
    for size, _pixels, payload in frames:
        dimension = 0 if size == 256 else size
        entries.append(
            struct.pack(
                "<BBBBHHII",
                dimension,
                dimension,
                0,
                0,
                0,
                32,
                len(payload),
                offset,
            )
        )
        payloads.append(payload)
        offset += len(payload)
    return b"".join([struct.pack("<HHH", 0, 1, len(frames)), *entries, *payloads])

def manifest_bytes(source_bytes: bytes, ico_bytes: bytes) -> bytes:
    lines = (
        "# Generated by build/windows/Generate-Icon.py; do not edit.\n"
        f"schema={SCHEMA}\n"
        "source=design/logo.png\n"
        f"sizes={','.join(map(str, SIZES))}\n"
        f"resample={RESAMPLE}\n"
        f"source_sha256={sha256(source_bytes)}\n"
        f"ico_sha256={sha256(ico_bytes)}\n"
    )
    return lines.encode("ascii")

def parse_ico_frames(data: bytes) -> dict[int, bytes]:
    if len(data) < 6:
        raise ValueError("ICO header is truncated")
    reserved, kind, count = struct.unpack_from("<HHH", data, 0)
    if reserved != 0 or kind != 1:
        raise ValueError("not a Windows icon container")
    if len(data) < 6 + 16 * count:
        raise ValueError("ICO directory is truncated")

    frames: dict[int, bytes] = {}
    for index in range(count):
        width, height, _colors, _reserved, _planes, bpp, length, offset = (
            struct.unpack_from("<BBBBHHII", data, 6 + 16 * index)
        )
        width = width or 256
        height = height or 256
        if width != height:
            raise ValueError(f"frame {index} is not square: {width}x{height}")
        if bpp != 32:
            raise ValueError(f"frame {width}px is {bpp}-bit, expected 32-bit RGBA")
        end = offset + length
        if offset < 6 + 16 * count or end > len(data):
            raise ValueError(f"frame {width}px points outside the ICO container")
        if width in frames:
            raise ValueError(f"duplicate {width}px frame")
        frames[width] = data[offset:end]
    return frames

def validate(source_bytes: bytes, ico_bytes: bytes) -> list[str]:
    failures: list[str] = []
    with Image.open(io.BytesIO(source_bytes)) as source:
        expected = expected_frames(source)

    try:
        actual = parse_ico_frames(ico_bytes)
    except ValueError as exc:
        return [str(exc)]

    if set(actual) != set(SIZES):
        failures.append(
            f"frame sizes are {sorted(actual)}, expected {list(SIZES)}"
        )

    for size, expected_pixels, _encoded in expected:
        payload = actual.get(size)
        if payload is None:
            continue
        try:
            with Image.open(io.BytesIO(payload)) as frame:
                rgba = frame.convert("RGBA")
                if rgba.size != (size, size):
                    failures.append(
                        f"{size}px directory frame decodes as {rgba.size[0]}x{rgba.size[1]}"
                    )
                elif rgba.tobytes() != expected_pixels:
                    failures.append(
                        f"{size}px frame is not the Lanczos resize of design/logo.png"
                    )
        except Exception as exc:  # Pillow reports several decoder error types.
            failures.append(f"{size}px frame cannot be decoded: {exc}")

    return failures

def replace_if_changed(path: Path, data: bytes) -> bool:
    if path.exists() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_bytes(data)
    temporary.replace(path)
    return True

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="validate ICO frames and the build hash manifest (default)",
    )
    mode.add_argument(
        "--write",
        action="store_true",
        help="regenerate the ICO and its build hash manifest",
    )
    args = parser.parse_args()

    if not SOURCE.is_file():
        print(f"error: canonical icon source is missing: {SOURCE}", file=sys.stderr)
        return 2

    source_bytes = SOURCE.read_bytes()
    with Image.open(io.BytesIO(source_bytes)) as source:
        ico_bytes = encode_ico(expected_frames(source))
    expected_manifest = manifest_bytes(source_bytes, ico_bytes)

    if args.write:
        changed_ico = replace_if_changed(ICO, ico_bytes)
        changed_manifest = replace_if_changed(MANIFEST, expected_manifest)
        action = "updated" if changed_ico or changed_manifest else "already current"
        print(f"Vkit icon {action}: {ICO}")
    elif not ICO.is_file():
        print(
            f"error: generated icon is missing: {ICO}\n"
            "run: python build/windows/Generate-Icon.py --write",
            file=sys.stderr,
        )
        return 1

    actual_ico = ICO.read_bytes()
    failures = validate(source_bytes, actual_ico)
    if actual_ico != ico_bytes:
        failures.append("ICO container bytes are not the deterministic generated output")
    if not MANIFEST.is_file() or MANIFEST.read_bytes() != expected_manifest:
        failures.append("build hash manifest is missing or stale")

    if failures:
        print("Vkit icon validation failed:", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        print(
            "run: python build/windows/Generate-Icon.py --write",
            file=sys.stderr,
        )
        return 1

    print(
        f"Vkit icon valid: {len(SIZES)} Lanczos frames, "
        f"SHA-256 {sha256(actual_ico)}"
    )
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
