fn rank(word: &str) -> Rank {
    match word {
        "eye" | "eyes" | "eyeball" | "eyeballs" | "eyelid" | "eyelids" | "eyelashes" | "lashes"
        | "brow" | "brows" | "cornea" | "iris" | "pupil" | "pupils" | "lacrimal" | "lacrimals"
        | "nose" | "nostril" | "nostrils" | "septum" | "bridge" | "philtrum" | "mouth" | "lip"
        | "lips" | "teeth" | "tongue" | "uvula" | "fangs" | "jaw" | "jawline" | "chin"
        | "cheek" | "cheeks" | "ear" | "ears" | "earlobes" | "face" | "head" | "cranium"
        | "forehead" | "fore" | "temples" | "bone" | "bones" | "bags" | "crows" | "marionette"
        | "slit" | "root" => Rank::Part,
        "area" | "all" => Rank::Region,
        "inner" | "in" | "outer" | "out" | "upper" | "top" | "up" | "lower" | "bottom" | "low"
        | "lo" | "down" | "center" | "middle" | "middlle" | "mid" | "side" => Rank::Direction,
        "left" | "l" | "right" | "r" => Rank::Side,
        "a" | "b" | "g" | "m" | "v" => Rank::Variant,
        _ => Rank::Shape,
    }
}

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
enum Rank {
    Part,
    Region,
    Direction,
    Shape,
    Side,
    Variant,
}

pub(super) fn compose(words: &[String]) -> Option<String> {
    let lowered_words = words
        .iter()
        .map(|word| word.to_ascii_lowercase())
        .collect::<Vec<_>>();
    let mut ranked: Vec<(String, Rank)> = Vec::with_capacity(words.len());
    let mut recognized = false;
    let mut skip = false;
    for (index, raw) in words.iter().enumerate() {
        if skip {
            skip = false;
            continue;
        }
        let lowered = lowered_words[index].clone();
        if let Some(compound) = compound(
            lowered.as_str(),
            lowered_words.get(index + 1).map(String::as_str),
        ) {
            ranked.push((compound.to_owned(), Rank::Part));
            recognized = true;
            skip = true;
            continue;
        }
        if lowered.chars().all(|character| character.is_ascii_digit()) {
            ranked.push((raw.clone(), Rank::Variant));
            continue;
        }
        let Some(name) = word(&lowered) else {
            ranked.push((raw.clone(), Rank::Shape));
            continue;
        };
        recognized = true;
        if !name.is_empty() {
            ranked.push((name.to_owned(), rank(&lowered)));
        }
    }
    if !recognized {
        return None;
    }
    ranked.sort_by_key(|(_, rank)| *rank);
    ranked.dedup_by(|left, right| left.0 == right.0);
    let noun = join(&ranked, |rank| rank <= Rank::Direction);
    let change = join(&ranked, |rank| rank == Rank::Shape);
    let tail = join(&ranked, |rank| rank >= Rank::Side);
    let mut label = match (noun.is_empty(), change.is_empty()) {
        (false, false) => format!("{noun}の{change}"),
        (false, true) => noun,
        (true, _) => change,
    };
    if !tail.is_empty() {
        if !label.is_empty() {
            label.push(' ');
        }
        label.push_str(&tail);
    }
    (!label.is_empty()).then_some(label)
}

fn join(ranked: &[(String, Rank)], keep: impl Fn(Rank) -> bool) -> String {
    ranked
        .iter()
        .filter(|(_, rank)| keep(*rank))
        .map(|(token, _)| token.as_str())
        .collect::<Vec<_>>()
        .concat()
}

